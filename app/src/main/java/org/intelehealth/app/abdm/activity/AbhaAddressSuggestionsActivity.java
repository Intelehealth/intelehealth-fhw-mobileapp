    private InputFilter filter = new InputFilter() {
        @Override
        public CharSequence filter(CharSequence source, int start, int end, Spanned dest, int dstart, int dend) {
            if (source != null && blockCharacterSet_ABHA_Address.contains(("" + source))) {
                return "";
            }
            return null;
        }
    };

    public boolean isValidAbhaAddress(String text) {
        // Check for @sbx presence
        String suffix = "@sbx";
        String prefix = text;

        if (text.contains(suffix)) {
            if (!text.endsWith(suffix)) {
                // '@sbx' is somewhere in the middle
                Toast.makeText(context, getString(R.string.sbx_suffix_is_only_allowed_at_the_end), Toast.LENGTH_SHORT).show();
                return false;
            }

            int count = (text.length() - text.replace(suffix, "").length()) / suffix.length();
            if (count > 1) {
                Toast.makeText(context, getString(R.string.sbx_suffix_can_only_appear_once), Toast.LENGTH_SHORT).show();
                return false;
            }

            prefix = text.substring(0, text.length() - suffix.length());
        }


        // Validate length of the prefix
        if (prefix.length() < 8 || prefix.length() > 18) {
            snackbarUtils.showSnackLinearLayoutParentSuccess(context, binding.llActionBar, getString(R.string.length_validation), false);
            return false;
        }

        if (!prefix.matches("^[A-Za-z0-9._]+$")) {
            snackbarUtils.showSnackLinearLayoutParentSuccess(context, binding.llActionBar, getString(R.string.characters_validation), false);
            return false;
        }

        if (prefix.startsWith(".") || prefix.startsWith("_") || prefix.endsWith(".") || prefix.endsWith("_")) {
            snackbarUtils.showSnackLinearLayoutParentSuccess(context, binding.llActionBar, getString(R.string.special_characters_position_validation), false);
            return false;
        }

        if (!doSpecialCharactersExistOnce(prefix)) {
            snackbarUtils.showSnackLinearLayoutParentSuccess(context, binding.llActionBar, getString(R.string.special_characters_count_validation), false);
            return false;
        }

        return true;
    }

    private boolean doSpecialCharactersExistOnce(String abhaAddress) {
        int countDot = 0;
        int countUnderscore = 0;
        char[] characterArray = abhaAddress.toCharArray();

        for (char current : characterArray) {
            if (current == '.') countDot++;
            if (current == '_') countUnderscore++;
        }

        return (countDot <= 1 && countUnderscore <= 1);
    }

    private void callSetPreferredABHAAddressAPI(String selectedChip) {
        if (!selectedChip.isEmpty()) {   // here you set this value to the Setter of the response variable and pass it to identification screen.
            if (selectedChip.equalsIgnoreCase(otpVerificationResponse.getABHAProfile().getPhrAddress().get(0))) {
                Intent dataIntent = new Intent(context, IdentificationActivity_New.class);
                dataIntent.putExtra("payload", otpVerificationResponse);    // not using this setPreferred response and using the previous aadhar api response itself...
                dataIntent.putExtra("accessToken", accessToken);
                startActivity(dataIntent);
                finish();
                return; // ie. selected is same as auto-generated than move ahead dont call setPrf api.
            } else {
                List<String> phrAddrList = new ArrayList<>();
                phrAddrList.add(selectedChip);
                phrAddrList.addAll(otpVerificationResponse.getABHAProfile().getPhrAddress());
                otpVerificationResponse.getABHAProfile().setPhrAddress(phrAddrList);
            }
        }

        // api - start
        String url = UrlModifiers.getSetPreferredABHAAddressUrl();
        EnrollSuggestionRequestBody body = new EnrollSuggestionRequestBody();
        body.setTxnId(otpVerificationResponse.getTxnId());
        body.setAbhaAddress(selectedChip);

        Single<Response<SetAbhaAddressResponse>> setPhrAddressResponse =
                AppConstants.apiInterface.PUSH_SET_PREFERRED_ABHA_ADDRESS(url, accessToken, body);


        new Thread(() -> setPhrAddressResponse
                .subscribeOn(Schedulers.io())
                .observeOn(AndroidSchedulers.mainThread())
                .subscribe(new DisposableSingleObserver<>() {
                    @Override
                    public void onSuccess(Response<SetAbhaAddressResponse> setAbhaAddressResponseResponse) {
                        handleSuccess(setAbhaAddressResponseResponse);
                    }

                    @Override
                    public void onError(Throwable e) {
                        Timber.tag(TAG).e("onError: onSuccess: callSetPreferredABHAAddressAPI%s", e.getMessage());
                    }
                })).start();
    }

    private void handleSuccess(Response<SetAbhaAddressResponse> setAbhaAddressResponseResponse) {
        if (setAbhaAddressResponseResponse.code() == 200) {// ie. setting this new abha address is done.
            try {
                abhaAddressET.setTextColor(getResources().getColor(R.color.green3));
                sessionManager.setIsPreferredAddressSet(true);
                Toast.makeText(context, getString(R.string.preferred_abha_address_is_set_successfully), Toast.LENGTH_SHORT).show();

                if (setAbhaAddressResponseResponse.body() != null) {
                    String preferredAbhaAddress = setAbhaAddressResponseResponse.body().getPreferredAbhaAddress();
                    String preferredAbhaAddressWithoutSbx = preferredAbhaAddress.replaceAll("@sbx", "");
                    List<String> phrAddresses = otpVerificationResponse.getABHAProfile().getPhrAddress();
                    phrAddresses.remove(preferredAbhaAddressWithoutSbx);

                    if (!preferredAbhaAddress.endsWith("@sbx")) {
                        preferredAbhaAddress = preferredAbhaAddress.concat("@sbx");
                    }

                    phrAddresses.add(0, preferredAbhaAddress);

                    Intent dataIntent = new Intent(context, IdentificationActivity_New.class);
                    dataIntent.putExtra("payload", otpVerificationResponse);    // not using this setPreferred response and using the previous aadhar api response itself...
                    dataIntent.putExtra("accessToken", accessToken);
                    dataIntent.putExtra("firstRequestFulfilled", firstRequestFulfilled);
                    startActivity(dataIntent);
                    finish();
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        } else if (setAbhaAddressResponseResponse.code() == 409) {
            abhaAddressET.setTextColor(getResources().getColor(R.color.red));
            Toast.makeText(context, "This ABHA address already exists, please use a different one", Toast.LENGTH_SHORT).show();
        } else {
            abhaAddressET.setTextColor(getResources().getColor(R.color.red));
            Toast.makeText(context, setAbhaAddressResponseResponse.raw().message(), Toast.LENGTH_SHORT).show();
        }
    }


